"""Register-wide evidence counts (andr-ops task 0042). Reads an exported copy of research main, prints docs/evidence-counts.md.
Counts distinct evidence lines per thesis: the top lists can restate archive lines, so an exact repeat counts once."""
import collections, glob, hashlib, os, re, sys

root = sys.argv[1]
version = hashlib.sha256(open(__file__, 'rb').read()).hexdigest()[:8]
rows, types, lanes = [], collections.Counter(), collections.Counter()
for f in sorted(glob.glob(f'{root}/topics/theses/B-*.md')):
    s = open(f, encoding='utf-8').read()
    m = re.search(r'^## Evidence\n(.*?)(?=^## |\Z)', s, re.S | re.M)
    sec = m.group(1) if m else ''
    lines = list(dict.fromkeys(l for l in sec.splitlines() if l.startswith('- ') and ' · ' in l))
    t, la = collections.Counter(), collections.Counter()
    for l in lines:
        p = l.split(' · ')
        if len(p) >= 5:
            t[p[2]] += 1
            la[p[3]] += 1
    tally = [int(x) for x in re.findall(r'^(?:For|Against): (\d+)', sec, re.M)]
    note = 'no tally line' if not tally else ('matches' if sum(tally) == len(lines) else f'tally says {sum(tally)}')
    rows.append((os.path.basename(f)[:5], len(lines), t, la, note))
    types.update(t)
    lanes.update(la)
fmt = lambda c: ', '.join(f'{k} {v}' for k, v in sorted(c.items())) or 'none'
print('# Evidence counts\n')
print(f'Generated by research:integrity (andr-ops task 0042, counts version {version}). Do not edit by hand. Counts distinct evidence lines on research main.\n')
print(f'**Total:** {sum(r[1] for r in rows)} lines across {len(rows)} theses.\n')
print(f'**By type:** {fmt(types)}.\n')
print(f'**By lane:** {fmt(lanes)}.\n')
print('| Thesis | Lines | Type | Lane | Hand tally |\n|---|---|---|---|---|')
for b, n, t, la, note in rows:
    print(f'| {b} | {n} | {fmt(t)} | {fmt(la)} | {note} |')
